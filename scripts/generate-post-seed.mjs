// Writes supabase/seed.sql: the Explore launch catalog as rows in the posts table.
// Regenerate after editing supabase/seed-posts.mjs: node scripts/generate-post-seed.mjs
import {writeFileSync} from 'node:fs';
import {SEED_POSTS} from '../supabase/seed-posts.mjs';

const text=value=>value===null||value===undefined?'null':`'${String(value).replace(/'/g,"''")}'`;
const list=values=>`array[${values.map(text).join(', ')}]::text[]`;
// Newest first, an hour apart, so the feed keeps the catalog's order and every
// post someone shares later appears above it.
const created=index=>text(new Date(Date.UTC(2026,9,1,12)-index*3600000).toISOString());
const columns=['slug','username','title','description','aesthetic','difficulty','hours','kind','color','trim_color','tools','materials','steps','image_path','image_width','image_height','likes','avatar','created_at'];
const rows=SEED_POSTS.map((p,i)=>`  (${[text(p.slug),text(p.username),text(p.title),text(p.description),text(p.aesthetic),text(p.difficulty),p.hours,text(p.kind),text(p.color),text(p.trim_color),list(p.tools),list(p.materials),list(p.steps),text(p.image_path),p.image_width,p.image_height,p.likes,p.avatar,created(i)].join(', ')})`);
const updates=columns.filter(c=>c!=='slug').map(c=>`${c} = excluded.${c}`).join(',\n  ');

writeFileSync('supabase/seed.sql',`-- Generated by scripts/generate-post-seed.mjs from supabase/seed-posts.mjs. Do not edit by hand.
-- The Explore launch catalog. Run after schema.sql in Supabase → SQL Editor.
-- Safe to run again: rows are matched by slug and refreshed in place.
insert into public.posts (${columns.join(', ')}) values
${rows.join(',\n')}
on conflict (slug) do update set
  ${updates};
`);
console.log(`Wrote ${SEED_POSTS.length} posts to supabase/seed.sql`);
